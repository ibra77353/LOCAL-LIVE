// تبسيط الاسم للمقارنة: حروف صغيرة، بلا حركات، ورمز واحد بين الكلمات.
function normalizeName(name) {
  return String(name == null ? '' : name)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9\u0600-\u06FF]+/g, ' ')
    .trim();
}

// يعيد الاسم العربي إن وُجد، وإلا الاسم الأصلي كما وصل من المصدر.
function arabicTeam(name) {
  const raw = String(name == null ? '' : name).trim();
  if (!raw) return raw;
  if (/[\u0600-\u06FF]/.test(raw)) return raw;
  return NAMES[normalizeName(raw)] || raw;
}

module.exports = { normalizeName, arabicTeam };
